package com.osp.bttp.dao.model.mview.db1;

public class ObjCombobox {
    private String name;
    private int values;

    public ObjCombobox(String name, int values) {
        this.name = name;
        this.values = values;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public int getValues() {
        return values;
    }

    public void setValues(int values) {
        this.values = values;
    }

    
}
